# PlantUML rather than graphviz, so that a generated diagram's nodes are hyperlinks to
# the elements they stand for. Navigating the architecture by clicking through it is worth
# more than the prose ordering of any one page, and it is the reason the link types above
# are populated at all.
needs_flow_engine = "plantuml"

# Both link types appear in a generated diagram unless a directive narrows it. Structure
# and dependency are different questions and a diagram showing only one of them misleads.
needs_flow_link_types = ["depends_on", "part_of"]

