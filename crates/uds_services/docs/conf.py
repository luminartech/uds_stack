"""Sphinx configuration for the uds_services documentation set.

The schema lives here. It is a contract with anything that consumes this set through
needs.json and links to these IDs, so a change here is a change to a published interface
rather than to local configuration.

`tools/validate_needs.py` enforces the parts of the schema that sphinx-needs has no
concept of. Keep the two in step: the permitted values below and the constants in that
script describe the same policy.

This set is deliberately close to `uds_session`'s, so that a reader who knows one knows
the other. It diverges in exactly four ways, each recorded at the point of divergence
below: the ID prefix, the `arch` need type, which fields that type requires, and the two
link types that make the architecture a graph.
"""

