release = "0.0.0"
# sphinx-needs keys needs.json by `version`, and a consumer pins to that key through
# needs_external_needs. Leaving it unset produces an empty key, which makes a committed
# snapshot impossible to pin to. Keep this in step with the crate version.
version = "0.0.0"

extensions = [
    "sphinx_needs",
    "sphinx_hextra",
    # Every diagram in this set is PlantUML, hand-authored or generated by `needflow`.
    # One diagram language rather than two: `sphinx.ext.graphviz` ships with Sphinx and
    # needs no Python dependency, but it cannot draw a sequence diagram and its raster
    # output is not clickable, so it would have to sit alongside this rather than replace
    # any of it.
    "sphinxcontrib.plantuml",
]

# --- diagrams -----------------------------------------------------------------------

# The renderer is a system dependency, not a Python one: `sphinxcontrib-plantuml` shells
# out to this command. Overridable by environment so a CI runner that installs the jar
# somewhere other than the PATH does not need this file edited.
#
# `-config` applies _plantuml/style.puml to every diagram, which is why no diagram in this
# set carries a skinparam block of its own. The path is absolute because the renderer is
# invoked with a working directory this file does not control.
_style = os.path.join(os.path.dirname(os.path.abspath(__file__)), "_plantuml", "style.puml")
plantuml = f"{os.environ.get('PLANTUML', 'plantuml')} -config {_style}"

# `svg_obj` is chosen for two reasons, and neither is cosmetic.
#
# It embeds through an `<object>` element, so the hyperlinks PlantUML writes into each node
# survive. `svg_img` renders identically and swallows every link, which would cost the
# generated diagrams their whole point — see `needs_flow_engine`.
#
# And it emits the SVG alone. Plain `svg` additionally writes a PNG fallback, which
# `needflow` then asks to scale; scaling a raster needs Pillow, and without it the build
# emits a warning — an error here, since warnings are errors. Adding an imaging library to
# a pinned documentation toolchain to produce a fallback no supported browser needs is the
# wrong trade.
plantuml_output_format = "svg_obj"

source_suffix = {
    ".rst": "restructuredtext",
}

exclude_patterns = [
    "_build",
    # Renderer configuration, not a document. Sphinx would otherwise warn that it is not
    # in any toctree, and warnings are errors.
    "_plantuml",
    # Working design documents, not part of the published set. They are not version
    # controlled, they go stale, and rules written for a single work item leak into later
    # ones if they are read as current. Never include them in published output.
    "superpowers",
    # Instructions addressed to the other repositories in the stack, not a description of
    # this crate. It is tracked so it can be carried between repositories, and excluded so
    # it is not published as though it were part of this crate's architecture.
    "stack-architecture-brief.md",
]

html_theme = "sphinx_hextra"

# The published site is HTML only, for the same reason the workflow prunes needs.json:
# that export is consumed as evidence against a committed snapshot, so no
# machine-consumable form may sit at a stable URL rebuilt on every push, where it could be
# pointed at instead. Sphinx otherwise copies every source document to
# `_sources/*.rst.txt` and links it from each page — the same content in another format.
# Pruning needs.json alone does not close that.
html_copy_source = False
html_show_sourcelink = False

# --- sphinx-needs schema ------------------------------------------------------------

